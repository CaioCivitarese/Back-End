function soma(x, y){
    const resultado = x + y;
    return resultado;

}

function sub(x, y){
    const resultado = x - y;
    return  resultado;

}

const resultadoSoma = soma(5, 3);
console.log("Resultado da soma: " + resultadoSoma);
const resultadoSub = sub(10, 4);
console.log("Resultado da subtração: " + resultadoSub);