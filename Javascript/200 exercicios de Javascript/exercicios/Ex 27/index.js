/*
Exercício 27: 
    Usando um laço for, imprima a tabuada de multiplicação do
    número 5.
Descrição: 
    Neste exercício, você deve criar um loop usando a estrutura de repetição for
    que percorra de 1 a 10 e imprima a tabuada de multiplicação do número 5.
*/

let N = 5;

for (let i = 1; i <= 10; i++){
    N *= i;
    console.log(N);
};
